"""Write what was found as a Kaitai Struct (.ksy) decoder: the format satnogs-decoders uses.

The output is a draft a decoder author can review and submit. Bytes nobody understood stay
as raw `unknown_*` blocks, so the layout is always complete and byte-exact. Each field's
doc says why it was identified (physics evidence), and Claude's unit and scale when given.
"""
from __future__ import annotations

import re
from pathlib import Path

KTYPE = {("u", 1): "u1", ("s", 1): "s1"}


def _ktype(f) -> tuple[str, str]:
    if f.signed == "f":
        return f"f4{f.endian}", ""
    if f.width == 3:  # Kaitai has no 3-byte int: a 24-bit bit-sized integer reads the same bytes
        note = " (signed 24-bit on the satellite; read here as unsigned)" if f.signed else ""
        return f"b24{f.endian}", note
    t = KTYPE.get(("s" if f.signed else "u", f.width)) or f"{'s' if f.signed else 'u'}{f.width}{f.endian}"
    return t, ""


def _ident(name: str, used: set) -> str:
    s = re.sub(r"[^a-z0-9_]", "_", name.lower()).strip("_") or "field"
    if s[0].isdigit():
        s = "f_" + s
    base, i = s, 2
    while s in used:
        s, i = f"{base}_{i}", i + 1
    used.add(s)
    return s


def _scale_expr(scale: str, ident: str) -> str | None:
    """'raw * 0.001' -> 'battery_voltage * 0.001', only for plain arithmetic."""
    if not scale or "raw" not in scale or scale.strip() == "raw":
        return None
    if not re.fullmatch(r"[raw0-9eE.\s*+\-/()]+", scale):
        return None
    return scale.replace("raw", ident)


def _q(s: str) -> str:
    return '"' + str(s).replace("\\", "\\\\").replace('"', "'") + '"'


def render(res, norad: int, header_bytes: int = 0) -> str:
    names = {g["offset"]: g for g in (res.names or {}).get("fields", [])}
    used: set = set()
    seq, inst, pos = [], [], 0
    if header_bytes:
        seq.append("  - id: ax25_header\n    size: %d\n    doc: AX.25 address and control header" % header_bytes)
    for f in sorted(res.fields, key=lambda f: f.offset):
        if f.offset < pos:
            continue
        if f.offset > pos:
            seq.append(f"  - id: unknown_{pos}\n    size: {f.offset - pos}")
        g = names.get(f.offset, {})
        ev = f"{f.kind} (score {f.score:.2f})"
        axes = f.detail.get("axes", 1)
        t, note = _ktype(f)
        base = _ident(g.get("name") or f"field_{f.offset}", used)
        unit = g.get("unit", "")
        doc = f"{g.get('category', f.kind)}" + (f", {unit}" if unit and unit != "unknown" else "") + \
              (f", {g['scale']}" if g.get("scale") else "") + f"; evidence: {ev}{note}"
        labels = {1: [""], 3: ["x", "y", "z"], 4: ["q0", "q1", "q2", "q3"]}.get(axes, [str(i) for i in range(axes)])
        idents = [base] if axes == 1 else [_ident(f"{base}_{a}", used) for a in labels]
        for ident in idents:
            seq.append(f"  - id: {ident}\n    type: {t}\n    doc: {_q(doc)}")
        expr = _scale_expr(g.get("scale", ""), idents[0]) if axes == 1 else None
        if expr:
            inst.append(f"  {idents[0]}_{_ident(unit or 'value', set())}:\n    value: {expr}")
        pos = f.offset + f.width * axes
    if pos < res.ft.length:
        seq.append(f"  - id: unknown_{pos}\n    size: {res.ft.length - pos}")
    key = re.sub(r"[^a-z0-9]+", "_", res.ft.key.lower()).strip("_")
    out = ["meta:", f"  id: shadowfield_{norad}_{key}", "  title: " + _q(f"NORAD {norad} {res.ft.key} (draft, generated by Shadowfield)"),
           "doc: |",
           "  Generated blind from raw SatNOGS frames by Shadowfield: field positions from orbital",
           "  physics (sunlight, shadow, orbit, IGRF, GNSS), names and units proposed by Claude.",
           "  Review before use. Bit-level flags and fields with no physical driver stay unknown.",
           *([f"  The payload is whitened ({res.layer}); undo that layer before parsing."] if getattr(res, "layer", None) else []),
           "seq:"] + seq
    if inst:
        out += ["instances:"] + inst
    return "\n".join(out) + "\n"


def write(results, norad: int, out_dir: Path) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = []
    for res in results:
        if not res.fields:
            continue
        raw0 = res.ft.df["raw"].iloc[0]
        header = len(raw0) - res.ft.length
        p = out_dir / f"{norad}_{re.sub(r'[^A-Za-z0-9]+', '_', res.ft.key)}.ksy"
        p.write_text(render(res, norad, header), encoding="utf-8")
        paths.append(p)
    return paths
